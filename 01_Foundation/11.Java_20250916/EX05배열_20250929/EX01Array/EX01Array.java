package EX01Array;
public class EX01Array {
    public static void main(String[] args) {
        
        //자료구조(Data Structure): 대량 데이터를 효율적으로 관리하기 위한 메커니즘
        // Array, Queue, Tree, List, Stack
        // Stack(스택): LIFO(Last In First Out) - 가장 나중에 들어온 데이터가 가장 먼저 나감
        // Queue(큐): FIFO(First In First Out) - 가장 먼저 들어온 데이터가 가장 먼저 나감
        // Tree(트리): 계층적 데이터 구조 - 부모-자식 관계
        // List(리스트): 순차적 데이터 구조 - 배열과 유사하지만 크기가 동적으로 변함


        // Array(배열): 고정 크기 데이터 구조 - 동일한 타입의 데이터를 연속적으로 저장
        // 번호를 붙여서 관리하는 자료구조: Array, List 


        // #1. 배열의 특징
        // 1. 같은 자료형만 하나로 묶을 수 있다.
        // 2. 인덱스 번호를 가지고 있다. 인덱스 번호는 0부터 차례로 1씩 증가한다.
        // 3. 크기가 고정적이다.



        // int[] numbers = new int[3];
        //int : 배열타입
        //[]: 배열선언
        // number : 배열에 대한 레퍼런스 변수
        // new : 배열생성
        // int : 선언한 배열 타입과 동일
        // [3] : 배열크기(길이, 용량, 개수) - 0부터 시작해서 2까지 (0,1,2)


        int[] numbers = new int[5];
        // numbers => [0, 0, 0, 0, 0] (int의 초기값) 
        // 주소를 참조하고 있다고 하여 reference 변수라고 함
        // Index(인덱스)란? 배열의 시작위치에서부터 데이터가 있는 상대적인 위치(0부터 시작)
        

        // 같은 종류의 데이터들이 순차적으로 저장되는 공간
        // 반복문을 이용하여 처리하기 좋ㅎ은 특징

        System.out.println("주소값 :" + numbers);
        // [I@279f2327
        // [I : int 배열
        // @ : 주소를 나타내는 구분자
        // 279f2327 : 16진수로 표현된 주소값
        // => 한번 더 들어가야 겠구나 ~ 라는 생각하기

        // numbers --> 5칸짜리 배열이 어디 있는지 주소값을 참조하는 레퍼런스 변수
        // new (keyword) => 레퍼런스 변수 생성 키워드




        // stack(스택) vs heap(힙)
        // stack : 메모리의 한 영역, 지역변수(함수내에 선언된 변수)들이 저장되는 공간
        // heap : 메모리의 한 영역, new 키워드로 생성된 객체(배열 포함)들이 저장되는 공간
        // stack에는 지역변수의 값(주소값)이 저장되고, heap에는 실제 객체가 저장됨
        // stack과 heap은 서로 다른 메모리 영역이므로, stack에 저장된 주소값을 통해 heap에 저장된 객체에 접근할 수 있음

        // int b = 5; 
        // int[] numbers = new int[5];
        // 너무 크기 때문에 stack에 저장할 수 없음
        // stack의 index는 heap에 저장된 객체의 주소값을 참조함
        // 배열은 너무 커서 stack에 저장할 수 없기 때문에 heap에 저장됨

        // 주소값이라는 개념이 왜 등장했나요?
        // : 자바에서는 데이터를 저장할 수 있는 공간이 분리되어 있다.
        // => 서로 다른 저장공간에 있는 데이터를 불러오기 위해서는 해당하는 데이터가 어디에 저장되어 있는지 주소값이 필요하다.

        // 1) 스택(Stack) 영역
        // : 비교적 작은 양의 데이터를 저장하는 공간
        // 2) 힙(Heap) 영역
        // : 커다랗고, 복잡한 데이터를 저장하는 공간, 배열등을 저장
        // : garbage collector(가비지 컬렉터)가 주기적으로 힙 영역을 검사하여 더 이상 참조되지 않는 객체를 자동으로 제거함
        // => 메모리 누수(memory leak)를 방지하고, 메모리 효율성을 높임



        // #2. 배열 안에 데이터를 저장하는 방법
        // --> 정확하게 방번호(index)를 지정한 후에 저장

        // 배열의 2번째 칸에 15라는 값을 집어 넣겠다. 
        numbers[1] = 15;


        System.out.println("============================================================");
        System.out.println("Index 활용 values: " + numbers[1]); // 15

       
        /*
        // Index를 초과하면 에러가 발생한다. numbers는 5번방 index가 없기 때문에 Error 발생한다
        numbers[5] = 20; // ArrayIndexOutOfBoundsException
        // Exception(예외) : 프로그램 실행 중에 발생하는 오류
        */


    }
}
