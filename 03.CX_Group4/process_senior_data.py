def clean_label(label):
    # 문자와 숫자만 남기고, 특수문자와 공백은 밑줄(_)로 변경
    label = re.sub(r'문\d+\.', '', label).strip()  # '문N.' 제거
    label = re.sub(r'[^a-zA-Z0-9가-힣\s]', '_', label) # 특수문자를 '_'로
    label = re.sub(r'\s+', '_', label) # 공백을 '_'로
    label = re.sub(r'__+', '_', label) # 중복 '_' 제거
    label = label.strip('_')
    return label

def create_column_mapping(design_doc_text):
    """파일 설계서 텍스트를 파싱하여 변수명:레이블 매핑 딕셔너리를 생성합니다."""
    mapping = {}
    lines = design_doc_text.strip().split('\n')
    for line in lines[1:]:  # 헤더 제외
        parts = line.split('\t')
        if len(parts) >= 3:
            var = parts[0].strip()
            label = parts[2].strip()
            # 더 짧고 명확한 레이블로 정제
            cleaned = clean_label(label)
            mapping[var] = cleaned
    return mapping

